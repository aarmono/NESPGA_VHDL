#!/usr/bin/env python3
"""Make the VHDL package sd_menu_stub from the assembled boot stub.

The package holds the stub, the top of the stub's 16 KB NROM PRG ROM, and
the iNES header that sd_menu streams into sdram_rom before it. sd_menu pads
the rest of the PRG ROM with 0xFF. With --nes, the whole image is also
written as a .nes file, for testing the stub in an emulator.
"""

import argparse

# NES 2.0, mapper 0, 1 16 KB PRG ROM bank, no CHR ROM, 8 KB of CHR RAM, no
# PRG RAM, NTSC
HEADER = bytes([0x4E, 0x45, 0x53, 0x1A, 0x01, 0x00, 0x00, 0x08,
                0x00, 0x00, 0x00, 0x07, 0x00, 0x00, 0x00, 0x00])
PRG_BYTES = 16384


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stub", help="the stub, as linked by ld65")
    parser.add_argument("vhdl", help="the package to write")
    parser.add_argument("--nes", help="the .nes image to write")
    args = parser.parse_args()

    with open(args.stub, "rb") as f:
        stub = f.read()
    assert len(stub) & (len(stub) - 1) == 0 and len(stub) <= PRG_BYTES, \
        "the stub must be a power of two bytes, at most %d" % PRG_BYTES

    def table(data):
        lines = []
        for i in range(0, len(data), 8):
            lines.append("        " + ", ".join(
                'x"%02X"' % b for b in data[i:i + 8]))
        return ",\n".join(lines)

    with open(args.vhdl, "w") as f:
        f.write("""\
-- Generated by board/de1/sd_menu/stub_rom.py from the boot stub,
-- board/de1/sd_menu/stub.s. Run make in board/de1/sd_menu after changing it
library IEEE;
use IEEE.std_logic_1164.all;
use work.nes_types.all;

package sd_menu_stub is

    constant STUB_PRG_BYTES : positive := %d;
    constant STUB_BYTES     : positive := %d;

    type stub_header_t is array(0 to 15) of data_t;
    type stub_rom_t is array(0 to STUB_BYTES - 1) of data_t;

    constant STUB_HEADER : stub_header_t :=
    (
%s
    );

    -- The top STUB_BYTES of the PRG ROM
    constant STUB_ROM : stub_rom_t :=
    (
%s
    );

end sd_menu_stub;
""" % (PRG_BYTES, len(stub), table(HEADER), table(stub)))

    if args.nes:
        with open(args.nes, "wb") as f:
            f.write(HEADER + b"\xFF" * (PRG_BYTES - len(stub)) + stub)


if __name__ == "__main__":
    main()
